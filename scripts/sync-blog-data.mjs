/**
 * Regenerates src/data/blogFilters.js and src/data/blogIndex.js from blog/*.md
 * and .docusaurus blog tag metadata (for accurate permalinks).
 *
 * Run: node scripts/sync-blog-data.mjs
 * Prefer after `npm run build` (or start) so tag permalinks are available.
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const blogDir = path.join(root, 'blog');
const outFilters = path.join(root, 'src/data/blogFilters.js');
const outIndex = path.join(root, 'src/data/blogIndex.js');
const tagCacheDir = path.join(
  root,
  '.docusaurus/docusaurus-plugin-content-blog/default/p',
);

/** Preferred chip order; only tags that exist are kept. Cap at MAX_FILTERS. */
const PREFERRED_FILTERS = [
  'How-to guides',
  'RPS',
  'API load testing',
  'Metrics & SLOs',
  'latency',
  'Fundamentals',
  'Best practices',
];
const MAX_FILTERS = 7;

const DISPLAY_LABELS = {
  latency: 'Latency',
};

function parseFrontMatter(text) {
  const match = text.match(/^---\n([\s\S]*?)\n---/);
  if (!match) {
    return null;
  }
  const body = match[1];
  const get = (key) => {
    const m = body.match(new RegExp(`^${key}:\\s*(.+)$`, 'm'));
    if (!m) {
      return '';
    }
    return m[1].trim().replace(/^["']|["']$/g, '');
  };
  const tagsBlock = body.match(/^tags:\n((?: {2}- .+\n?)+)/m);
  const tags = [];
  if (tagsBlock) {
    for (const line of tagsBlock[1].trim().split('\n')) {
      const label = line.replace(/^\s*-\s*/, '').trim().replace(/^["']|["']$/g, '');
      if (label) {
        tags.push(label);
      }
    }
  }
  return {
    title: get('title'),
    slug: get('slug'),
    description: get('description'),
    date: get('date'),
    tags,
  };
}

function loadTagPermalinks() {
  const map = new Map();
  if (!fs.existsSync(tagCacheDir)) {
    return map;
  }
  for (const name of fs.readdirSync(tagCacheDir)) {
    if (!name.startsWith('blog-tags-') || name.includes('page-')) {
      continue;
    }
    let data;
    try {
      data = JSON.parse(fs.readFileSync(path.join(tagCacheDir, name), 'utf8'));
    } catch {
      continue;
    }
    const tag = data?.tag;
    if (!tag?.label || !tag?.permalink) {
      continue;
    }
    if ((data.listMetadata?.page ?? 1) !== 1) {
      continue;
    }
    map.set(tag.label, tag.permalink);
  }
  return map;
}

function slugifyTag(label) {
  return label
    .toLowerCase()
    .replace(/&/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function displayLabel(label) {
  return DISPLAY_LABELS[label] || label;
}

function main() {
  const tagPermalinks = loadTagPermalinks();
  const counts = new Map();
  const posts = [];

  const files = fs
    .readdirSync(blogDir)
    .filter((f) => /^\d{4}-\d{2}-\d{2}-.+\.mdx?$/.test(f))
    .sort()
    .reverse();

  for (const file of files) {
    const fm = parseFrontMatter(
      fs.readFileSync(path.join(blogDir, file), 'utf8'),
    );
    if (!fm?.slug) {
      continue;
    }
    for (const tag of fm.tags) {
      counts.set(tag, (counts.get(tag) || 0) + 1);
    }
    posts.push({
      title: fm.title,
      slug: fm.slug,
      permalink: `/blog/${fm.slug}`,
      description: fm.description,
      date: fm.date || file.slice(0, 10),
      tags: fm.tags,
    });
  }

  const filters = [];
  for (const label of PREFERRED_FILTERS) {
    if (!counts.has(label)) {
      continue;
    }
    const permalink =
      tagPermalinks.get(label) || `/blog/tags/${slugifyTag(label)}`;
    filters.push({
      label: displayLabel(label),
      count: counts.get(label),
      permalink,
    });
    if (filters.length >= MAX_FILTERS) {
      break;
    }
  }

  // Fill remaining slots by count if preferred list is short
  if (filters.length < MAX_FILTERS) {
    const used = new Set(PREFERRED_FILTERS.filter((l) => counts.has(l)));
    const rest = [...counts.entries()]
      .filter(([label]) => !used.has(label))
      .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
    for (const [label, count] of rest) {
      filters.push({
        label: displayLabel(label),
        count,
        permalink:
          tagPermalinks.get(label) || `/blog/tags/${slugifyTag(label)}`,
      });
      if (filters.length >= MAX_FILTERS) {
        break;
      }
    }
  }

  const filtersSrc = `/** Auto-generated by scripts/sync-blog-data.mjs — do not edit by hand. */
export const BLOG_TOTAL_POSTS = ${posts.length};

export const BLOG_FILTERS = ${JSON.stringify(filters, null, 2)};
`;

  const indexSrc = `/** Auto-generated by scripts/sync-blog-data.mjs — do not edit by hand. */
export const BLOG_POSTS = ${JSON.stringify(posts, null, 2)};
`;

  fs.mkdirSync(path.dirname(outFilters), {recursive: true});
  fs.writeFileSync(outFilters, filtersSrc);
  fs.writeFileSync(outIndex, indexSrc);
  console.log(
    `Wrote ${filters.length} filters + ${posts.length} posts → src/data/`,
  );
}

main();
